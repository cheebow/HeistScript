export type PixelMap = string[];

export const TILE = 16;

/** 左右反転 */
export function flipH(map: PixelMap): PixelMap {
  return map.map((row) => row.split('').reverse().join(''));
}

/** 歩行フレーム: 下3行の左半分を1行上へずらす */
export function walkFrame(map: PixelMap): PixelMap {
  const out = map.map((r) => r.split(''));
  const h = out.length;
  const w = out[0]!.length;
  for (let y = h - 3; y < h; y++) {
    for (let x = 0; x < w / 2; x++) {
      const below = y + 1 < h ? out[y + 1]![x]! : '.';
      out[y]![x] = below;
    }
  }
  // 最下行の左半分は空に
  for (let x = 0; x < w / 2; x++) out[h - 1]![x] = '.';
  return out.map((r) => r.join(''));
}

